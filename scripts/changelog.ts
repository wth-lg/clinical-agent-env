// Builds results/CHANGELOG.md from per-PR fragments, so two open PRs never edit the same file.
// A PR adds one file, results/changelog.d/<YYYYMMDD>-<id>.md, holding its one entry line
// ("- ..."), and leaves CHANGELOG.md alone. CHANGELOG.md is HEADER and then every fragment in
// file-name order, each line ending in a comment that names its fragment, written by this script.
//
//   pnpm changelog [--drop-removed] [results-dir]   rewrite CHANGELOG.md from the fragments
//   pnpm changelog --check [results-dir]            check only; results-dir defaults to results
//
// --check fails on a malformed fragment name or text, two fragments with one entry, a header
// that is not HEADER, a line that names no fragment or a fragment that does not exist (an entry
// added by hand, often with the tag of the line above copied), or folded lines out of file-name
// order. A fragment not folded yet, or changed since its fold, passes as stale: a PR does not
// rebuild CHANGELOG.md, or every merge would conflict again. The rewrite refuses those same
// lines instead of dropping them; --drop-removed lets it drop a line whose fragment was removed
// on purpose. It names each line it restores from a changed fragment (a hand edit of a folded
// line is undone that way). Names starting with '.' are skipped.
// Each finding prints path: reason. Exit codes: 0 ok, 1 finding, 2 usage error.
import { existsSync, readdirSync, readFileSync, statSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

// After a change here, delete CHANGELOG.md and run the rewrite: it refuses a header it did not write.
const HEADER = `# Results changelog

<!-- Generated by \`pnpm changelog\`; do not edit by hand. Each PR adds its one entry line ("- ...") as results/changelog.d/<YYYYMMDD>-<id>.md and leaves this file alone (<id> is the branch or PR name, so two PRs never pick one file); \`pnpm changelog\`, run on main and never in a PR, rebuilds it from every fragment in file-name order, and \`pnpm changelog --check\` (in pnpm test) fails a line added here by hand. Entries merged since the last rebuild are in results/changelog.d/. -->

`;
const FRAGMENT_NAME = /^(\d{4})(\d{2})(\d{2})-[a-z0-9][a-z0-9.-]*\.md$/;
// A folded line: the entry, then the fragment it came from in a comment GitHub does not render.
const FOLDED = /^(- .*) <!-- changelog\.d\/([^ ]+) -->$/;

type Fragment = { name: string; entry: string };

function validDate(y: string, m: string, d: string): boolean {
  const date = new Date(Date.UTC(Number(y), Number(m) - 1, Number(d)));
  return date.getUTCFullYear() === Number(y) && date.getUTCMonth() === Number(m) - 1 && date.getUTCDate() === Number(d);
}

// File-name order compares names without .md, so p17i-b3 comes before p17i-b3-follow-up.
const order = (name: string) => name.replace(/\.md$/, '');
const byName = (a: string, b: string) => (order(a) < order(b) ? -1 : order(a) > order(b) ? 1 : 0);

const show = (line: string) => `'${line.length > 100 ? `${line.slice(0, 100)}…` : line}'`;
const folded = (f: Fragment) => `${f.entry} <!-- changelog.d/${f.name} -->`;

function validName(name: string): boolean {
  const [, y = '', m = '', d = ''] = FRAGMENT_NAME.exec(name) ?? [];
  return y !== '' && validDate(y, m, d);
}

function readFragments(dir: string, findings: string[]): Fragment[] {
  const out: Fragment[] = [];
  const seen = new Map<string, string>();
  for (const name of readdirSync(dir).sort(byName)) {
    if (name.startsWith('.')) continue; // .gitkeep, and .DS_Store or editor files git ignores
    const path = join(dir, name);
    if (!validName(name)) {
      findings.push(`${path}: name must be <YYYYMMDD>-<id>.md with a real date and an id of a-z, 0-9, '.' and '-'`);
      continue;
    }
    if (!statSync(path).isFile()) {
      findings.push(`${path}: is not a file`);
      continue;
    }
    const entry = readFileSync(path, 'utf8').replace(/\n$/, '');
    if (entry.includes('\n') || entry.includes('\r') || !/^- \S/.test(entry) || entry.includes('<!--')) {
      findings.push(`${path}: must hold one line starting '- ', the entry as CHANGELOG.md shows it, with no HTML comment`);
      continue;
    }
    const twin = seen.get(entry);
    if (twin) findings.push(`${path}: repeats the entry of ${twin}`);
    seen.set(entry, path);
    out.push({ name, entry });
  }
  return out;
}

function main(): void {
  const args = process.argv.slice(2);
  const check = args.includes('--check');
  const dropRemoved = args.includes('--drop-removed');
  const rest = args.filter((a) => a !== '--check' && a !== '--drop-removed');
  if (rest.length > 1 || rest.some((a) => a.startsWith('-')) || (check && dropRemoved)) {
    process.stderr.write('usage: pnpm changelog [--drop-removed] [results-dir] | pnpm changelog --check [results-dir]\n');
    process.exit(2);
  }
  const root = rest[0] ?? 'results';
  const file = join(root, 'CHANGELOG.md');
  const dir = join(root, 'changelog.d');
  if (!existsSync(dir)) {
    process.stderr.write(`changelog: no such directory: ${dir}\n`);
    process.exit(2);
  }

  const findings: string[] = [];
  const fragments = readFragments(dir, findings);
  // A missing CHANGELOG.md is a finding for --check; the rewrite creates it.
  const text = existsSync(file) ? readFileSync(file, 'utf8') : check ? '' : HEADER;
  // Fragment names not folded as they are now: not folded yet, or changed since.
  const stale = new Set<string>();
  // Folded lines whose fragment is gone (dropped with --drop-removed), and lines the rewrite
  // restores from a changed fragment.
  const gone: string[] = [];
  const restored: string[] = [];
  if (!text.startsWith(HEADER)) {
    findings.push(`${file}: the header must be the one scripts/changelog.ts writes; add an entry as changelog.d/<YYYYMMDD>-<id>.md instead`);
  } else {
    // Each folded line names its fragment, once, in file-name order. A line that is the
    // current fragment text is up to date; any other named line is stale and the rewrite redoes it.
    const lines = new Set(text.slice(HEADER.length).split('\n'));
    for (const f of fragments) if (!lines.has(folded(f))) stale.add(f.name);
    const current = new Set(fragments.map(folded));
    const names = new Set(fragments.map((f) => f.name));
    let last = '';
    for (const [i, line] of text.slice(HEADER.length).replace(/\n$/, '').split('\n').entries()) {
      if (line === '') continue;
      const where = `${file}:${HEADER.split('\n').length + i}`;
      const name = FOLDED.exec(line)?.[2];
      if (name === undefined || !validName(name)) {
        findings.push(`${where}: ${show(line)} names no fragment; add it as changelog.d/<YYYYMMDD>-<id>.md instead`);
        continue;
      }
      if (last && byName(name, last) <= 0) {
        if (check) findings.push(`${where}: changelog.d/${name} is out of file-name order or folded twice; run pnpm changelog`);
        continue;
      }
      last = name;
      if (current.has(line)) continue;
      if (names.has(name)) {
        stale.add(name);
        restored.push(`${where} from changelog.d/${name}`);
      } else if (dropRemoved) {
        gone.push(`${where} changelog.d/${name}`);
      } else {
        findings.push(`${where}: ${show(line)} names changelog.d/${name}, which does not exist; add that fragment, or if it was removed on purpose run pnpm changelog --drop-removed on main`);
      }
    }
  }

  for (const f of findings) process.stdout.write(`${f}\n`);
  if (findings.length) {
    process.stderr.write(`changelog: ${findings.length} finding(s)${check ? '' : `, ${file} not written`}\n`);
    process.exit(1);
  }
  if (check) {
    const left = stale.size ? `${stale.size} not folded yet or changed since; a PR leaves them, the fold runs on main` : 'all folded';
    process.stderr.write(`changelog: ok, ${fragments.length} fragment(s), ${left}\n`);
    return;
  }
  for (const g of gone) process.stderr.write(`changelog: dropped ${g}, which no fragment holds now\n`);
  for (const r of restored) process.stderr.write(`changelog: restored ${r}\n`);
  writeFileSync(file, HEADER + fragments.map((f) => `${folded(f)}\n`).join(''));
  process.stderr.write(`changelog: wrote ${file}, ${fragments.length} fragment(s)\n`);
}

main();
